-- VIEWS
CREATE OR REPLACE VIEW `v_room_overview` AS
SELECT r.room_id, r.room_code, r.floor, r.area_size, r.base_price, r.elec_price, r.water_price, r.status AS room_status, r.amenities, r.images, a.area_id, a.area_name, a.address, a.district, a.city, a.latitude, a.longitude, a.host_id, h.full_name AS host_name, h.phone_number AS host_phone
FROM rooms r JOIN motel_areas a ON a.area_id = r.area_id JOIN users h ON h.user_id = a.host_id;

CREATE OR REPLACE VIEW `v_active_contracts` AS
SELECT c.contract_id, c.contract_code, c.start_date, c.end_date, DATEDIFF(c.end_date, CURRENT_DATE) AS days_until_expiry, c.actual_rent_price, c.elec_price_override, c.water_price_override, c.status, r.room_id, r.room_code, r.floor, r.elec_price AS room_elec_price, r.water_price AS room_water_price, a.area_id, a.area_name, a.host_id, t.user_id AS tenant_id, t.full_name AS tenant_name, t.phone_number AS tenant_phone, t.email AS tenant_email
FROM contracts c JOIN rooms r ON r.room_id = c.room_id JOIN motel_areas a ON a.area_id = r.area_id JOIN users t ON t.user_id = c.tenant_id WHERE c.status = 'ACTIVE';

CREATE OR REPLACE VIEW `v_invoice_detail` AS
SELECT i.invoice_id, i.invoice_code, i.billing_month, i.billing_year, i.due_date, i.elec_old, i.elec_new, i.elec_price, i.water_old, i.water_new, i.water_price, i.rent_amount, i.elec_amount, i.water_amount, i.service_amount, i.total_amount, i.status AS invoice_status, i.paid_at, c.contract_id, c.contract_code, r.room_id, r.room_code, a.area_id, a.area_name, a.host_id, t.user_id AS tenant_id, t.full_name AS tenant_name, t.phone_number AS tenant_phone
FROM invoices i JOIN contracts c ON c.contract_id = i.contract_id JOIN rooms r ON r.room_id = c.room_id JOIN motel_areas a ON a.area_id = r.area_id JOIN users t ON t.user_id = c.tenant_id;

CREATE OR REPLACE VIEW `v_missing_invoices_this_month` AS
SELECT r.room_id, r.room_code, a.area_id, a.area_name, a.host_id, c.contract_id, c.tenant_id, t.full_name AS tenant_name, t.phone_number AS tenant_phone, MONTH(CURRENT_DATE) AS check_month, YEAR(CURRENT_DATE) AS check_year
FROM rooms r JOIN motel_areas a ON a.area_id = r.area_id JOIN contracts c ON c.room_id = r.room_id AND c.status = 'ACTIVE' JOIN users t ON t.user_id = c.tenant_id
WHERE r.status = 'RENTED' AND NOT EXISTS (SELECT 1 FROM invoices i WHERE i.contract_id = c.contract_id AND i.billing_month = MONTH(CURRENT_DATE) AND i.billing_year = YEAR(CURRENT_DATE));

CREATE OR REPLACE VIEW `v_admin_dashboard` AS
SELECT
  (SELECT COUNT(*) FROM motel_areas) AS total_areas,
  (SELECT COUNT(*) FROM rooms) AS total_rooms,
  (SELECT COUNT(*) FROM rooms WHERE status = 'RENTED') AS rented_rooms,
  (SELECT COUNT(*) FROM rooms WHERE status = 'AVAILABLE') AS available_rooms,
  (SELECT COUNT(*) FROM rooms WHERE status = 'MAINTENANCE') AS maintenance_rooms,
  (SELECT COUNT(*) FROM rooms WHERE status = 'DEPOSITED') AS deposited_rooms,
  (SELECT COUNT(*) FROM users WHERE role_id = 2) AS total_hosts,
  (SELECT COUNT(*) FROM users WHERE role_id = 2 AND is_active = 1) AS active_hosts,
  (SELECT COUNT(*) FROM users WHERE role_id = 3) AS total_tenants,
  (SELECT COUNT(*) FROM users WHERE role_id = 3 AND is_active = 1) AS active_tenants,
  (SELECT COUNT(*) FROM contracts WHERE status = 'ACTIVE') AS active_contracts,
  (SELECT COUNT(*) FROM invoices WHERE status IN ('UNPAID','OVERDUE')) AS pending_invoices,
  (SELECT COUNT(*) FROM issues WHERE status IN ('OPEN','PROCESSING')) AS open_issues,
  (SELECT COALESCE(SUM(total_amount),0) FROM invoices WHERE status = 'PAID' AND billing_month = MONTH(CURRENT_DATE) AND billing_year = YEAR(CURRENT_DATE)) AS revenue_this_month,
  (SELECT COALESCE(SUM(total_amount),0) FROM invoices WHERE status IN ('UNPAID','OVERDUE')) AS total_debt_outstanding;

